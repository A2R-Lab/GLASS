# ───── gemm_batched_1d ──────────────────────────────────────────────────────
# Compares the 1D SIMT batched (glass::nvidia::block::gemm_batched_1d) against
# the 2D cuBLASDx batched (glass::nvidia::block::gemm_batched). The launches differ
# (1D = TC*BATCH threads; 2D = dim3(TC, BATCH)). The autotune still picks the
# faster wall-time per op — that's what cublasdx_wins_batched<> answers.
_GEMM_BATCHED_MICROBENCH = _BENCH_PREAMBLE + textwrap.dedent("""

    static const int M = {M}, N = {N}, K = {K};
    static const int BATCH = {BATCH};
    // Cap threads-per-matrix so the 2D launch dim3(BTC, BATCH) and the 1D
    // launch BTC*BATCH stay within the 1024-thread/block limit. The default
    // TC=64 with BATCH=32 would request 2048 threads, so the launch fails
    // silently — recorded as a bogus 0.000us before this cap + leg_failed().
    static const int BTC = (TC * BATCH > 1024) ? (1024 / BATCH) : TC;

    namespace glass {{ namespace nvidia {{ namespace block {{   // block:: required since the 2026-07-30 namespace restructure
        DEFINE_NVIDIA_GEMM_BLOCKDIM(M, N, K, BTC)
        DEFINE_NVIDIA_GEMM_BATCHED_BLOCKDIM(M, N, K, BATCH, BTC)
    }}}}}}

    __global__ void k_simt(float** As, float** Bs, float** Cs, volatile float* sink, int iters) {{
        for (int rep = 0; rep < iters; rep++) {{
            glass::nvidia::block::gemm_batched_1d<float, M, N, K, BATCH, BTC>(
                1.f, As, Bs, 0.f, Cs);
            __syncthreads();
            if (threadIdx.x == 0) sink[rep & 0xFF] = Cs[0][0];
            __syncthreads();
        }}
    }}

    __global__ void k_cublasdx(float** As, float** Bs, float** Cs,
                                volatile float* sink, int iters) {{
        extern __shared__ __align__(16) char smem[];
        for (int rep = 0; rep < iters; rep++) {{
            glass::nvidia::block::gemm_batched<float, M, N, K, BATCH, BTC>(
                1.f, As, Bs, 0.f, Cs, smem);
            __syncthreads();
            if (threadIdx.x == 0 && threadIdx.y == 0) sink[rep & 0xFF] = Cs[0][0];
            __syncthreads();
        }}
    }}

    int main(int argc, char** argv) {{
        int iters = (argc > 1) ? atoi(argv[1]) : 5000;
        float *dA, *dB, *dC, *dSink;
        // SIMT batched_1d expects contiguous A/B/C arrays of BATCH*(MxN/NxK/MxK).
        cudaMalloc(&dA, BATCH * M * N * sizeof(float));
        cudaMalloc(&dB, BATCH * N * K * sizeof(float));
        cudaMalloc(&dC, BATCH * M * K * sizeof(float));
        cudaMalloc(&dSink, 256 * sizeof(float));

        // cuBLASDx gemm_batched takes ptr-arrays; build them by indexing into
        // the same contiguous buffers above.
        float **dAs, **dBs, **dCs;
        cudaMalloc(&dAs, BATCH * sizeof(float*));
        cudaMalloc(&dBs, BATCH * sizeof(float*));
        cudaMalloc(&dCs, BATCH * sizeof(float*));
        float *hAs[BATCH], *hBs[BATCH], *hCs[BATCH];
        for (int b = 0; b < BATCH; b++) {{
            hAs[b] = dA + b * M * N;
            hBs[b] = dB + b * N * K;
            hCs[b] = dC + b * M * K;
        }}
        cudaMemcpy(dAs, hAs, BATCH * sizeof(float*), cudaMemcpyHostToDevice);
        cudaMemcpy(dBs, hBs, BATCH * sizeof(float*), cudaMemcpyHostToDevice);
        cudaMemcpy(dCs, hCs, BATCH * sizeof(float*), cudaMemcpyHostToDevice);
        constexpr size_t smem =
            glass::nvidia::block::gemm_batched_scratch_bytes<float, M, N, K, BATCH, BTC>();

        // SIMT batched_1d launches 1D with BTC*BATCH threads, ptr-array args.
        k_simt<<<1, BTC * BATCH>>>(dAs, dBs, dCs, dSink, 100);
        bool simt_ok = !leg_failed("simt");
        // cuBLASDx batched launches 2D dim3(BTC, BATCH).
        cudaFuncSetAttribute(k_cublasdx, cudaFuncAttributeMaxDynamicSharedMemorySize, smem);
        k_cublasdx<<<1, dim3(BTC, BATCH), smem>>>(dAs, dBs, dCs, dSink, 100);
        bool cdx_ok = !leg_failed("cublasdx");

        if (simt_ok) {{
            TIME3("simt", (k_simt<<<1, BTC * BATCH>>>(dAs, dBs, dCs, dSink, iters)));
        }}

        if (cdx_ok) {{
            TIME3("cublasdx", (k_cublasdx<<<1, dim3(BTC, BATCH), smem>>>(dAs, dBs, dCs, dSink, iters)));
        }}

        cudaFree(dA); cudaFree(dB); cudaFree(dC); cudaFree(dSink);
        cudaFree(dAs); cudaFree(dBs); cudaFree(dCs);
        return 0;
    }}
""")


# ─── Per-API config: shape grid + template + specialization formatter ─────

_SQUARE = [3, 4, 5, 6, 7, 8, 12, 14, 16, 24, 32, 48, 64]


def _spec_gemm(m, n, k, sms):
    return f"cublasdx_wins<{m:>2},{n:>3},{k:>3},{sms:>5}>"


def _spec_gemv(m, n, sms):
    return f"cublasdx_wins_gemv<{m:>2},{n:>3},{sms:>5}>"


def _spec_gemv_strided(m, n, rs, sms):
    return f"cublasdx_wins_gemv_strided<{m:>2},{n:>3},{rs:>3},{sms:>5}>"


def _spec_gemm_strided(m, n, k, a_rs, b_rs, sms):
    return (f"cublasdx_wins_gemm_strided<"
            f"{m:>2},{n:>3},{k:>3},{a_rs:>3},{b_rs:>3},{sms:>5}>")


def _spec_batched(m, n, k, batch, sms):
    return f"cublasdx_wins_batched<{m:>2},{n:>3},{k:>3},{batch:>3},{sms:>5}>"


