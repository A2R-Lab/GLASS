def detect_sm() -> int:
    out = subprocess.check_output(
        ["nvidia-smi", "--query-gpu=compute_cap", "--format=csv,noheader"],
        text=True, stderr=subprocess.DEVNULL,
    ).strip().split("\n")[0].strip()
    major, minor = out.split(".")
    return int(f"{major}{minor}0")


