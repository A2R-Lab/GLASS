# ─── Per-API microbench templates ───────────────────────────────────────────
#
# Each API_CONFIGS entry carries:
#   - shape_keys: tuple of shape-grid parameter names (used for parsing
#                 --shapes and for `microbench.format(**placeholders)`).
#   - default_shapes: list of tuples matching shape_keys.
#   - microbench: textwrap-dedented C++ source with `{key}` placeholders.
#                 Must compile to a binary that prints two lines:
#                     simt     <us_per_op>
#                     cublasdx <us_per_op>
#   - spec_fmt: callable (shape_values..., sms) -> the C++ specialization
#               name (e.g. "cublasdx_wins_gemv<6,6,1200>"). The output
#               file prepends "template <> constexpr bool ", appends "()
#               { return <bool>; }".
#   - label_fmt: callable (shape) -> short human label for progress prints.
#
# To add an API: append an entry to API_CONFIGS; main loop picks it up.

# NOTE: the preamble is concatenated with each per-API microbench template
# and the WHOLE combined string is passed through `str.format(**placeholders)`.
# That means literal `{` / `}` must appear as `{{` / `}}` here (and in every
# microbench template below) so .format leaves them alone.
_BENCH_PREAMBLE = textwrap.dedent("""
    // Auto-generated by bench/autotune.py
    #include <cstdio>
    #include <cstdlib>
    #include <ctime>
    #ifdef GLASS_BENCH_CUBLASDX
    #include <cublasdx.hpp>
    #endif
    #include "../glass-nvidia.cuh"

    static const int TC = 64;

    static double elapsed_us(struct timespec a, struct timespec b) {{
        return (double)(b.tv_sec - a.tv_sec) * 1e6
             + (double)(b.tv_nsec - a.tv_nsec) * 1e-3;
    }}

    // A launched kernel that errors (shared-mem overflow, >1024 threads,
    // cuBLASDx reject) must be reported as a FAILURE, not timed as a silent
    // ~0us. After a launch, leg_failed() syncs, checks the error, and on
    // failure prints a non-numeric marker line so bench/autotune.py records
    // the leg as "measurement failed -> SIMT default" instead of believing a
    // bogus 0.000us. Returns true on failure.
    static bool leg_failed(const char* leg) {{
        cudaError_t e = cudaDeviceSynchronize();
        if (e == cudaSuccess) e = cudaGetLastError();
        if (e != cudaSuccess) {{
            printf("%s FAILED %s\\n", leg, cudaGetErrorString(e));
            return true;
        }}
        return false;
    }}

    // best-of-3 + spread (methodology audit 2026-08-11): the min of 3 timed
    // legs estimates the clean time (noise is one-sided on a quiet GPU); the
    // spread (max/min - 1, %) rides on the output line so autotune.py can
    // flag cells whose jitter exceeds the decision margin.
    #define TIME3(LEG, LAUNCH) do {{ \
        double _best = 1e30, _worst = 0.0; \
        for (int _t = 0; _t < 3; _t++) {{ \
            struct timespec _a, _b; \
            clock_gettime(CLOCK_MONOTONIC, &_a); \
            LAUNCH; cudaDeviceSynchronize(); \
            clock_gettime(CLOCK_MONOTONIC, &_b); \
            double _us = elapsed_us(_a, _b) / iters; \
            if (_us < _best) _best = _us; \
            if (_us > _worst) _worst = _us; \
        }} \
        printf("%s %.6f spread %.1f\\n", LEG, _best, (_worst / _best - 1.0) * 100.0); \
    }} while (0)
""").strip()


